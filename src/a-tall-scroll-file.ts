export function computeScrollDelta(args: {
  cardTopPx: number;
  headerOffsetPx: number;
  paddingPx: number;
}): number {
  const target = args.headerOffsetPx + args.paddingPx;
  if (args.cardTopPx >= target) {
    return 0;
  }
  return args.cardTopPx - target;
}

